namespace Coding4Coffee.WinForms.Commands.Enums
{
    /// <summary>
    /// Specifies the direction to switch tabs in a <see cref="System.Windows.Forms.TabControl"/>.
    /// </summary>
    public enum SwitchTabDirection : byte
    {
        /// <summary>
        /// Switches to the next tab page.
        /// </summary>
        Next = 0,

        /// <summary>
        /// Switches to the previous tab page.
        /// </summary>
        Previous = 1    
    }
}
